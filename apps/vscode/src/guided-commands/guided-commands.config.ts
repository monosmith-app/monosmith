const text = (answers: GuidedAnswers, key: string): string => {
  const value = answers[key]

  return typeof value === 'string' ? value.trim() : ''
}
const list = (answers: GuidedAnswers, key: string): string[] => {
  const value = answers[key]

  return Array.isArray(value) ? value : []
}

