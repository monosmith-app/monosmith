package derivefile

import (
	"strings"
	"testing"

	"github.com/monosmith-app/monosmith/packages/plugin-sdk/protocol"
)

func jsonKeys(keys map[string]any) protocol.DerivedFile {
	return protocol.DerivedFile{Path: "p/tsconfig.json", Mode: protocol.DeriveKeys, Format: "json", Renderer: "r", Version: 1, Keys: keys}
}

func TestKeysModeKeepsTheKeysItDoesNotOwn(t *testing.T) {
	disk := []byte("{\n  \"extends\": \"../../tsconfig.json\",\n  \"references\": [{\"path\": \"../old\"}],\n  \"include\": [\"src\"]\n}\n")
	f := jsonKeys(map[string]any{"references": []any{map[string]any{"path": "../core"}}})
	out, err := Merge(f, disk, true)
	if err != nil {
		t.Fatal(err)
	}
	s := string(out)
	for _, want := range []string{`"extends": "../../tsconfig.json"`, `"include"`, `../core`} {
		if !strings.Contains(s, want) {
			t.Errorf("merged file lacks %s:\n%s", want, s)
		}
	}
	if strings.Contains(s, "../old") || strings.Index(s, "extends") > strings.Index(s, "references") {
		t.Errorf("owned key kept its old value or moved:\n%s", s)
	}
	present, _, err := Present(f, out)
	wanted, _ := Wanted(f)
	if err != nil || string(present) != string(wanted) {
		t.Errorf("present %q, wanted %q (%v)", present, wanted, err)
	}
}

func TestKeysModeCreatesAMissingFile(t *testing.T) {
	out, err := Merge(jsonKeys(map[string]any{"references": []any{}}), nil, false)
	if err != nil || !strings.Contains(string(out), `"references": []`) {
		t.Fatalf("%q %v", out, err)
	}
}

func TestTomlKeysAreSetInTheirTable(t *testing.T) {
	f := protocol.DerivedFile{Path: "pyproject.toml", Mode: protocol.DeriveKeys, Format: "toml", Table: "tool.smith", Renderer: "r", Keys: map[string]any{"name": "web", "deps": []string{"a", "b"}}}
	disk := "[project]\nname = \"web\"\n\n[tool.smith]\nname = \"old\" # why\nother = 1\n"
	out, err := Merge(f, []byte(disk), true)
	if err != nil {
		t.Fatal(err)
	}
	want := "[project]\nname = \"web\"\n\n[tool.smith]\nname = \"web\" # why\nother = 1\ndeps = [\"a\", \"b\"]\n"
	if string(out) != want {
		t.Errorf("got\n%s\nwant\n%s", out, want)
	}
	got, _, _ := Present(f, out)
	wanted, _ := Wanted(f)
	if string(got) != string(wanted) {
		t.Errorf("present %q, wanted %q", got, wanted)
	}
}

func TestRegionModeReplacesOnlyBetweenMarkers(t *testing.T) {
	f := protocol.DerivedFile{Path: "jest.config.js", Mode: protocol.DeriveRegion, Comment: "//", Renderer: "node.jest.display-name", Content: "  displayName: 'web',"}
	disk := "module.exports = {\n  // smith:begin node.jest.display-name\n  displayName: 'old',\n  // smith:end node.jest.display-name\n  preset: 'x',\n}\n"
	out, err := Merge(f, []byte(disk), true)
	if err != nil {
		t.Fatal(err)
	}
	want := "module.exports = {\n  // smith:begin node.jest.display-name\n  displayName: 'web',\n  // smith:end node.jest.display-name\n  preset: 'x',\n}\n"
	if string(out) != want {
		t.Errorf("got\n%s", out)
	}
	if _, err := Merge(f, []byte("module.exports = {}\n"), true); err != ErrNoMarkers {
		t.Errorf("no markers: %v", err)
	}
	if _, found, _ := Present(f, []byte("x\n")); found {
		t.Error("Present found a region without markers")
	}
}

func TestWholeFileCarriesAHeaderWhenTheFormatHasComments(t *testing.T) {
	f := protocol.DerivedFile{Path: "a.cfg", Mode: protocol.DeriveFile, Comment: "#", Renderer: "r", Version: 2, Content: "x = 1"}
	wanted, err := Wanted(f)
	if err != nil || !strings.HasPrefix(string(wanted), "# Generated by smith (r v2)") || !strings.HasSuffix(string(wanted), "x = 1\n") {
		t.Fatalf("%q %v", wanted, err)
	}
	f.Comment = ""
	if w, _ := Wanted(f); string(w) != "x = 1\n" {
		t.Errorf("no comment, no header: %q", w)
	}
}
