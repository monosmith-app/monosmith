package derivefile

import (
	"bytes"
	"encoding/json"
	"fmt"
	"sort"
	"strconv"
	"strings"

	"github.com/monosmith-app/monosmith/packages/plugin-sdk/protocol"
	"github.com/monosmith-app/monosmith/packages/plugin-sdk/tomltext"
)

// Wanted is the content smith owns in the file when it is as the renderer
// wants it, in the canonical form that is hashed. It returns an error when the
// renderer's output does not fit its mode.
func Wanted(f protocol.DerivedFile) ([]byte, error) {
	switch f.Mode {
	case protocol.DeriveFile:
		return []byte(Header(f) + ensureNewline(norm(f.Content))), nil
	case protocol.DeriveRegion:
		if f.Comment == "" {
			return nil, fmt.Errorf("%s: a region needs the comment leader of its file for the markers", f.Path)
		}
		return []byte(ensureNewline(norm(f.Content))), nil
	case protocol.DeriveKeys:
		return keysContent(f, f.Keys)
	}
	return nil, fmt.Errorf("%s: unknown ownership mode %q", f.Path, f.Mode)
}

// Present is the content smith owns as the file on disk has it, in the same
// canonical form as Wanted. found is false when the owned part cannot be told
// apart: a region whose markers are gone. It returns an error when the file is
// not valid for its format.
func Present(f protocol.DerivedFile, disk []byte) (owned []byte, found bool, err error) {
	switch f.Mode {
	case protocol.DeriveFile:
		return []byte(norm(string(disk))), true, nil
	case protocol.DeriveRegion:
		_, body, _, ok := splitRegion(norm(string(disk)), f)
		return []byte(body), ok, nil
	case protocol.DeriveKeys:
		keys, err := presentKeys(f, disk)
		if err != nil {
			return nil, false, err
		}
		out, err := keysContent(f, keys)
		return out, true, err
	}
	return nil, false, fmt.Errorf("%s: unknown ownership mode %q", f.Path, f.Mode)
}

// Absent reports whether the owned part of the file on disk is empty: a region
// with nothing between its markers, or a keys file with none of the owned
// keys. Smith treats that as a deleted derived file, not as an edit.
func Absent(f protocol.DerivedFile, disk []byte) (bool, error) {
	switch f.Mode {
	case protocol.DeriveRegion:
		_, body, _, ok := splitRegion(norm(string(disk)), f)
		return ok && strings.TrimSpace(body) == "", nil
	case protocol.DeriveKeys:
		have, err := presentKeys(f, disk)
		return len(have) == 0, err
	}
	return false, nil
}

// HasAllKeys reports whether a keys-mode file on disk still has every key the
// renderer owns, whatever their values.
func HasAllKeys(f protocol.DerivedFile, disk []byte) (bool, error) {
	have, err := presentKeys(f, disk)
	if err != nil {
		return false, err
	}
	return len(have) == len(f.Keys), nil
}

// Header is the generated header of a whole file; empty when the format has
// no comments.
func Header(f protocol.DerivedFile) string {
	if f.Comment == "" {
		return ""
	}
	return fmt.Sprintf("%s Generated by smith (%s v%d). Do not edit: change the facts and run `smith derive`,\n%s or run `smith derive --eject %s` to own this file.\n", f.Comment, f.Renderer, f.Version, f.Comment, f.Path)
}

// norm turns CRLF into LF, so a checkout with another line ending hashes the same.
func norm(s string) string { return strings.ReplaceAll(s, "\r\n", "\n") }

func ensureNewline(s string) string {
	if s == "" || strings.HasSuffix(s, "\n") {
		return s
	}
	return s + "\n"
}

// keysContent renders keys in the canonical form of the file's format.
func keysContent(f protocol.DerivedFile, keys map[string]any) ([]byte, error) {
	switch f.Format {
	case "json":
		var b bytes.Buffer
		enc := json.NewEncoder(&b)
		enc.SetEscapeHTML(false)
		if err := enc.Encode(keys); err != nil {
			return nil, err
		}
		return b.Bytes(), nil
	case "toml":
		var b strings.Builder
		for _, k := range sortedKeys(keys) {
			raw, err := tomlValue(keys[k])
			if err != nil {
				return nil, fmt.Errorf("%s: key %s: %w", f.Path, k, err)
			}
			b.WriteString(k + " = " + raw + "\n")
		}
		return []byte(b.String()), nil
	}
	return nil, fmt.Errorf("%s: keys mode needs the format json or toml, got %q", f.Path, f.Format)
}

// presentKeys reads the owned keys that the file has.
func presentKeys(f protocol.DerivedFile, disk []byte) (map[string]any, error) {
	out := map[string]any{}
	switch f.Format {
	case "json":
		var all map[string]any
		dec := json.NewDecoder(bytes.NewReader(disk))
		dec.UseNumber()
		if err := dec.Decode(&all); err != nil {
			return nil, fmt.Errorf("%s is not a JSON object smith can read (comments are not supported): %w", f.Path, err)
		}
		for k := range f.Keys {
			if v, ok := all[k]; ok {
				out[k] = v
			}
		}
	case "toml":
		for k := range f.Keys {
			if raw, ok := tomltext.Raw(string(disk), f.Table, k); ok {
				out[k] = rawTOML(raw)
			}
		}
	}
	return out, nil
}

// rawTOML marks a value read from a TOML file as text that is written as is.
type rawTOML string

func tomlValue(v any) (string, error) {
	switch t := v.(type) {
	case rawTOML:
		return string(t), nil
	case string:
		return strconv.Quote(t), nil
	case bool:
		return strconv.FormatBool(t), nil
	case int:
		return strconv.Itoa(t), nil
	case float64:
		return strconv.FormatFloat(t, 'g', -1, 64), nil
	case json.Number:
		return t.String(), nil
	case []string:
		items := make([]any, len(t))
		for i, s := range t {
			items[i] = s
		}
		return tomlValue(items)
	case []any:
		parts := make([]string, len(t))
		for i, item := range t {
			p, err := tomlValue(item)
			if err != nil {
				return "", err
			}
			parts[i] = p
		}
		return "[" + strings.Join(parts, ", ") + "]", nil
	}
	return "", fmt.Errorf("a TOML value must be a string, number, boolean or array of those, got %T", v)
}

func sortedKeys(m map[string]any) []string {
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	return keys
}
