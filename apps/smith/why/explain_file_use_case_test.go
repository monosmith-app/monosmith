func testInputs(t *testing.T) Inputs {
	t.Helper()
	g, err := projectgraph.New([]*projectgraph.Project{
		{Project: protocol.Project{Name: "web", Root: "apps/web", Kind: protocol.ProjectApp, Language: "node", Stack: "react-vitest"}, Deps: []string{"ui"}},
		{Project: protocol.Project{Name: "ui", Root: "libs/ui", Kind: protocol.ProjectLib, Language: "node"}},
	})
	if err != nil {
		t.Fatal(err)
	}
	rec := derivelock.Record{Schema: 1}
	rec.Set(derivelock.Entry{Path: "apps/web/tsconfig.lib.json", Owner: derivelock.OwnerSmith, Renderer: "node.tsconfig.references", Version: 1, Mode: "keys"})
	rec.Set(derivelock.Entry{Path: "apps/web/jest.config.js", Owner: derivelock.OwnerYou, Renderer: "node.jest.display-name", Version: 1, Mode: "region"})
	plan := &derive.Plan{Items: []derive.Item{{
		File:   protocol.DerivedFile{Project: "web", Path: "apps/web/tsconfig.lib.json", Renderer: "node.tsconfig.references"},
		Status: derive.StatusDrift, Detail: "someone edited the file",
	}}}
	return Inputs{
		Record: rec, Plan: plan, Graph: g,
		Stacks: map[string]workspace.StackConfig{"react-vitest": {Choices: []string{"react", "vitest"}}},
		Head: func(p string) string {
			switch p {
			case ".github/workflows/ci.yml":
				return "# Generated by smith from the workspace's projects.\n"
			case "AGENTS.md":
				return "# Notes\n" + agentdoc.BeginMarker + "\n"
			}
			return ""
		},
	}
}

func TestADerivedFileNamesOwnerRendererInputAndWayToChange(t *testing.T) {
	e := Explain(testInputs(t), "apps/web/tsconfig.lib.json")
	if e.Kind != KindDerived || e.Owner != OwnerSmith || !e.Known {
		t.Fatalf("got %+v", e)
	}
	if !strings.Contains(e.Rule, "node.tsconfig.references v1") || !strings.Contains(e.Source, "depends on ui") {
		t.Errorf("rule %q source %q", e.Rule, e.Source)
	}
	if len(e.Parts) != 1 || e.Parts[0].State != "drift" {
		t.Errorf("parts %+v", e.Parts)
	}
	if !strings.Contains(strings.Join(e.Change, "\n"), "smith derive --eject apps/web/tsconfig.lib.json") {
		t.Errorf("change %v", e.Change)
	}
}

func TestAnEjectedFileIsYours(t *testing.T) {
	e := Explain(testInputs(t), "apps/web/jest.config.js")
	if e.Kind != KindEjected || e.Owner != OwnerYou {
		t.Fatalf("got %+v", e)
	}
}

func TestAProjectFileNamesTheStackAndChoices(t *testing.T) {
	e := Explain(testInputs(t), "apps/web/src/main.tsx")
	if e.Kind != KindProject || e.Owner != OwnerYou || e.Project != "web" {
		t.Fatalf("got %+v", e)
	}
	if !strings.Contains(e.Source, "react-vitest") || !strings.Contains(e.Source, "react, vitest") {
		t.Errorf("source %q", e.Source)
	}
}

func TestAFileSmithDoesNotKnowIsSaidPlainly(t *testing.T) {
	e := Explain(testInputs(t), "notes/todo.txt")
	if e.Known || e.Kind != KindUnknown || !strings.Contains(e.Summary, "does not know") {
		t.Fatalf("got %+v", e)
	}
	if e.Change == nil {
		t.Error("change must be an empty list, not null")
	}
}

func TestGeneratedFilesNameTheirCommand(t *testing.T) {
	in := testInputs(t)
	if e := Explain(in, ".github/workflows/ci.yml"); e.Kind != KindGenerated || e.Rule != "smith ci generate" {
		t.Errorf("pipeline: %+v", e)
	}
	if e := Explain(in, "AGENTS.md"); e.Kind != KindGenerated || e.Rule != "smith agent file" {
		t.Errorf("agents: %+v", e)
	}
	if e := Explain(in, workspace.FileName); e.Kind != KindWorkspace || e.Owner != OwnerYou {
		t.Errorf("config: %+v", e)
	}
	if e := Explain(in, derivelock.FileName); e.Owner != OwnerSmith {
		t.Errorf("lock: %+v", e)
	}
}
