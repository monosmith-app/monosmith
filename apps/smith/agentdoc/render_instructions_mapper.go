package agentdoc

import (
	"fmt"
	"slices"
	"sort"
	"strings"

	"github.com/monosmith-app/monosmith/libs/plugin-vertical-slices/languages"
)

// forbiddenFolders are the junk-drawer folder names the vertical-slices check
// refuses, singular spellings only, sorted: the agent file and the check read
// the same list.
func forbiddenFolders() []string {
	var out []string
	for name := range languages.ForbiddenFolders {
		if !strings.HasSuffix(name, "s") || !languages.ForbiddenFolders[strings.TrimSuffix(name, "s")] {
			out = append(out, name)
		}
	}
	sort.Strings(out)
	return out
}

// generatedNote is the first line of the generated region.
const generatedNote = "<!-- Generated by `smith agent file` from smith.toml and smith.lock. Do not edit between the markers: change the workspace, then run `smith agent file`. -->"

// Render is the generated region for the facts, markers included. It ends
// with a newline. The same facts give the same text.
func Render(f Facts) string {
	var b strings.Builder
	b.WriteString(BeginMarker + "\n" + generatedNote + "\n\n")
	fmt.Fprintf(&b, "## Where code goes\n\n")
	b.WriteString(whereCodeGoes(f))
	b.WriteString("\n## Naming and file roles\n\n")
	b.WriteString(naming(f))
	b.WriteString("\n## Add a project\n\n")
	b.WriteString("Create a project with smith. Do not copy a folder by hand.\n\n```sh\nsmith add <app|lib|package> <name> --lang <language>\nsmith add app web --lang node --with react,vitest\n```\n\n")
	b.WriteString("`smith kinds` lists the kinds, `smith choices` lists the choices for `--with`, and `smith stacks` lists the stacks. A project follows what its sibling projects already do.\n")
	b.WriteString("\n## Done means\n\n")
	b.WriteString(done(f))
	b.WriteString("\n## Derived files: do not edit by hand\n\n")
	b.WriteString(derived(f))
	b.WriteString("\n## Projects and their choices\n\n")
	b.WriteString(projects(f))
	b.WriteString(EndMarker + "\n")
	return b.String()
}

func whereCodeGoes(f Facts) string {
	if len(f.Architectures) == 0 {
		return "This workspace turns on no architecture convention, so smith checks no code layout. Follow the layout of the sibling projects.\n"
	}
	var b strings.Builder
	b.WriteString("These architectures are in force. Code that breaks them fails `smith lint`.\n\n")
	for _, a := range f.Architectures {
		fmt.Fprintf(&b, "- `%s`: %s.\n", a.Name, a.Meaning)
		if a.Rules != "" {
			fmt.Fprintf(&b, "  Rules: %s.\n", strings.TrimSuffix(a.Rules, "."))
		}
		for _, l := range a.Layers {
			fmt.Fprintf(&b, "  - `%s` (folders %s): %s.\n", l.Name, backticked(l.Folders), strings.TrimSuffix(l.Meaning, "."))
		}
	}
	if hasArchitecture(f, "vertical-slices") {
		b.WriteString("\nOne folder is one slice: one outcome, flat, with no sub-folders. Put new code in the slice it belongs to, or make a new slice. Do not make a folder named " + backticked(forbiddenFolders()) + " (or their plurals).\n")
	}
	return b.String()
}

func naming(f Facts) string {
	if !hasArchitecture(f, "vertical-slices") {
		return "Name a new file like the files next to it.\n"
	}
	var b strings.Builder
	b.WriteString("A file is named for the role it plays. The roles are " + backticked(languages.Roles) + ".\n\n")
	for _, lang := range f.Languages {
		if rule, ok := namingByLanguage[lang]; ok {
			fmt.Fprintf(&b, "- %s: %s.\n", lang, rule)
		}
	}
	b.WriteString("\nRun `smith slices check` to check the names.\n")
	return b.String()
}

func done(f Facts) string {
	var b strings.Builder
	b.WriteString("Run these before you say a change is done.\n\n```sh\n")
	for _, t := range f.Tasks {
		fmt.Fprintf(&b, "smith %s\n", t)
	}
	b.WriteString("smith doctor\n")
	if f.Derive {
		b.WriteString("smith derive --check\n")
	}
	b.WriteString("smith ci verify\n```\n\n")
	b.WriteString("`smith ci verify` is the same check as CI. A change is done when it passes.\n")
	if f.Branch != "" {
		fmt.Fprintf(&b, "Commits use Conventional Commits: a merge to `%s` releases what they describe.\n", f.Branch)
	}
	return b.String()
}

func derived(f Facts) string {
	if !f.Derive {
		return "Derived files are off in this workspace. `smith.lock` lists none.\n"
	}
	var b strings.Builder
	if len(f.Derived) == 0 {
		b.WriteString("Derived files are on, and `smith.lock` lists no file smith owns yet.\n")
	} else {
		b.WriteString("smith writes these files from facts and the project graph. A hand edit is reported as drift and never kept silently. Change the input, then run `smith derive`.\n\n")
		for _, p := range f.Derived {
			fmt.Fprintf(&b, "- `%s`\n", p)
		}
	}
	b.WriteString("\nTo own one of them, run `smith derive --eject <file>`. `smith why <file>` says who owns any file and why.\n")
	if len(f.Ejected) > 0 {
		b.WriteString("\nThese were ejected and are yours to edit:\n\n")
		for _, p := range f.Ejected {
			fmt.Fprintf(&b, "- `%s`\n", p)
		}
	}
	return b.String()
}

func projects(f Facts) string {
	if len(f.Projects) == 0 {
		return "The workspace has no project yet.\n\n"
	}
	var b strings.Builder
	b.WriteString("| Project | Folder | Kind | Language | Stack | Choices |\n|---|---|---|---|---|---|\n")
	for _, p := range f.Projects {
		choices := "none"
		if len(p.Choices) > 0 {
			choices = strings.Join(p.Choices, ", ")
		}
		stack := p.Stack
		if stack == "" {
			stack = "none"
		}
		fmt.Fprintf(&b, "| %s | `%s` | %s | %s | %s | %s |\n", p.Name, p.Root, p.Kind, p.Language, stack, choices)
	}
	b.WriteString("\n`smith explain <project>` shows how its tasks resolved.\n")
	return b.String()
}

func hasArchitecture(f Facts, name string) bool {
	return slices.ContainsFunc(f.Architectures, func(a Architecture) bool { return a.Name == name })
}

func backticked(names []string) string {
	out := make([]string, len(names))
	for i, n := range names {
		out[i] = "`" + n + "`"
	}
	return strings.Join(out, ", ")
}
