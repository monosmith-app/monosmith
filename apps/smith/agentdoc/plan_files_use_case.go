package agentdoc

import (
	"errors"
	"os"
	"path/filepath"
)

// claudeRegion is the generated region of CLAUDE.md: an import of AGENTS.md.
const claudeRegion = BeginMarker + "\n<!-- Generated by `smith agent file`. Claude Code reads the instructions from AGENTS.md. -->\n@AGENTS.md\n" + EndMarker + "\n"

const agentsHeader = "# AGENTS.md\n\nInstructions for AI coding agents that work in this workspace. Write your own notes outside the smith markers.\n"

const claudeHeader = "# CLAUDE.md\n"

// FileChange is one file the command writes: its new text, and whether that
// differs from the file on disk.
type FileChange struct {
	// Path is relative to the workspace root.
	Path string
	// Content is the whole file as it should be.
	Content string
	// Exists tells whether the file is on disk.
	Exists bool
	// Differs is true when the file is missing or its text is not Content.
	Differs bool
}

// PlanFiles computes AGENTS.md, and CLAUDE.md when claude is true, for the
// facts under root. It writes nothing. It returns an error when a file cannot
// be read or its smith markers are broken.
func PlanFiles(root string, f Facts, claude bool) ([]FileChange, error) {
	want := []struct{ path, header, region string }{{AgentsFile, agentsHeader, Render(f)}}
	if claude {
		want = append(want, struct{ path, header, region string }{ClaudeFile, claudeHeader, claudeRegion})
	}
	var out []FileChange
	for _, w := range want {
		raw, err := os.ReadFile(filepath.Join(root, w.path))
		exists := err == nil
		if err != nil && !errors.Is(err, os.ErrNotExist) {
			return nil, err
		}
		content, err := Merge(string(raw), exists, w.header, w.region)
		if err != nil {
			return nil, &BrokenFileError{Path: w.path}
		}
		out = append(out, FileChange{Path: w.path, Content: content, Exists: exists, Differs: !exists || content != string(raw)})
	}
	return out, nil
}

// BrokenFileError says which file has broken markers.
type BrokenFileError struct {
	// Path is the file.
	Path string
}

// Error implements error.
func (e *BrokenFileError) Error() string {
	return e.Path + ": " + ErrBrokenMarkers.Error()
}

// Unwrap lets errors.Is match ErrBrokenMarkers.
func (e *BrokenFileError) Unwrap() error { return ErrBrokenMarkers }
