// Compare reads a file and says how it differs from the plugin's standard for
// it.
//
// Parameters: root is the workspace; f is the plugin's standard.
// Returns: the difference and true when the file is not as the standard has
// it; false when it is.
// Errors: the standard does not fit its mode, or the file on disk does not
// parse in its format.
func Compare(root string, f protocol.StandardFileContent) (Difference, bool, error) {
	if !filepath.IsLocal(filepath.FromSlash(f.Path)) {
		return Difference{}, false, fmt.Errorf("%s: a standard file must be inside the workspace", f.Path)
	}
	df, err := derived(f)
	if err != nil {
		return Difference{}, false, err
	}
	full := filepath.Join(root, filepath.FromSlash(f.Path))
	disk, err := os.ReadFile(full)
	exists := err == nil
	if err != nil && !errors.Is(err, fs.ErrNotExist) {
		return Difference{}, false, err
	}
	if exists {
		same, err := matches(f, df, disk)
		if err != nil {
			return Difference{}, false, fmt.Errorf("%s: %w", f.Path, err)
		}
		if same {
			return Difference{}, false, nil
		}
	}
	merged, err := derivefile.Merge(df, disk, exists)
	if err != nil {
		return Difference{}, false, fmt.Errorf("%s: %w", f.Path, err)
	}
	d := Difference{File: f, Exists: exists, Old: disk, New: merged}
	if exists && f.Mode == protocol.StandardFile {
		d.Copy = copyPath(root, f.Path)
	}
	return d, true, nil
}

// derived is the standard as the derive machinery reads it. No comment leader
// is set, so a whole file gets no "generated by smith" header: the team owns
// it once it is written.
func derived(f protocol.StandardFileContent) (protocol.DerivedFile, error) {
	df := protocol.DerivedFile{Project: f.Project, Path: f.Path, Renderer: "standard", Version: 1}
	switch f.Mode {
	case protocol.StandardFile:
		df.Mode, df.Content = protocol.DeriveFile, f.Content
	case protocol.StandardKeys:
		if f.Format != "json" && f.Format != "toml" {
			return df, fmt.Errorf("%s: keys of a %q file cannot be set; json or toml", f.Path, f.Format)
		}
		if len(f.Keys) == 0 {
			return df, fmt.Errorf("%s: a keys standard names no key", f.Path)
		}
		keys, err := keyValues(f)
		if err != nil {
			return df, err
		}
		df.Mode, df.Format, df.Table, df.Keys = protocol.DeriveKeys, f.Format, f.Table, keys
	default:
		return df, fmt.Errorf("%s: unknown standard mode %q", f.Path, f.Mode)
	}
	return df, nil
}

// keyValues are the standard's keys as the derive machinery writes them: a
// JSON value stays raw, so the members of an object keep the plugin's order
// (the conditions of a package.json "exports" are read in order); a TOML value
// is decoded, since TOML is written from Go values.
func keyValues(f protocol.StandardFileContent) (map[string]any, error) {
	out := make(map[string]any, len(f.Keys))
	for k, raw := range f.Keys {
		if !json.Valid(raw) {
			return nil, fmt.Errorf("%s: the value of key %s is not JSON", f.Path, k)
		}
		if f.Format == "json" {
			out[k] = raw
			continue
		}
		var v any
		dec := json.NewDecoder(bytes.NewReader(raw))
		dec.UseNumber()
		if err := dec.Decode(&v); err != nil {
			return nil, fmt.Errorf("%s: key %s: %w", f.Path, k, err)
		}
		out[k] = v
	}
	return out, nil
}

// matches says whether the file on disk is as the standard has it. A whole
// file and the keys of a TOML file are compared as derive compares them; the
// keys of a JSON file are compared as compacted JSON, so a value whose members
// are in another order differs (an "exports" whose "default" comes before
// "types" resolves differently).
func matches(f protocol.StandardFileContent, df protocol.DerivedFile, disk []byte) (bool, error) {
	if f.Mode == protocol.StandardKeys && f.Format == "json" {
		var have map[string]json.RawMessage
		if err := json.Unmarshal(jsondoc.StripComments(disk), &have); err != nil {
			return false, fmt.Errorf("not a JSON object smith can read: %w", err)
		}
		for k, want := range f.Keys {
			got, ok := have[k]
			if !ok || !sameJSON(got, want) {
				return false, nil
			}
		}
		return true, nil
	}
	wanted, err := derivefile.Wanted(df)
	if err != nil {
		return false, err
	}
	present, _, err := derivefile.Present(df, disk)
	if err != nil {
		return false, err
	}
	return bytes.Equal(wanted, present), nil
}

// sameJSON compares two JSON values byte for byte once compacted.
func sameJSON(a, b json.RawMessage) bool {
	var ca, cb bytes.Buffer
	if json.Compact(&ca, a) != nil || json.Compact(&cb, b) != nil {
		return false
	}
	return bytes.Equal(ca.Bytes(), cb.Bytes())
}

// copyPath is where a replaced file is kept: <path>.pre-smith, or
// <path>.pre-smith-2 and up when an earlier copy is there, so no copy is lost.
func copyPath(root, path string) string {
	candidate := path + CopySuffix
	for n := 2; ; n++ {
		if _, err := os.Stat(filepath.Join(root, filepath.FromSlash(candidate))); errors.Is(err, fs.ErrNotExist) {
			return candidate
		}
		candidate = path + CopySuffix + "-" + strconv.Itoa(n)
	}
}

// keyList names the keys of a keys standard, sorted.
func keyList(keys map[string]json.RawMessage) string {
	names := make([]string, 0, len(keys))
	for k := range keys {
		names = append(names, k)
	}
	sort.Strings(names)
	return strings.Join(names, ", ")
}
