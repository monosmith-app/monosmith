func TestEmbeddedInstallerEqualsTheRepositoryInstaller(t *testing.T) {
	root, err := os.ReadFile("../../../install.sh")
	if err != nil {
		t.Skipf("repository install.sh not reachable: %v", err)
	}
	if strings.ReplaceAll(string(root), "\r\n", "\n") != strings.ReplaceAll(installerSource, "\r\n", "\n") {
		t.Fatal("apps/smith/cipipeline/smith_installer.sh differs from install.sh: run `cp install.sh apps/smith/cipipeline/smith_installer.sh`")
	}
}

func TestInstallScriptKeepsShebangAndChecksumVerification(t *testing.T) {
	got := InstallScript()
	if !strings.HasPrefix(got, "#!/bin/sh\n# Generated by smith") {
		t.Fatalf("header must follow the shebang: %q", got[:60])
	}
	for _, want := range []string{"checksums.txt", "checksum mismatch", "Do not edit"} {
		if !strings.Contains(got, want) {
			t.Errorf("installer lacks %q", want)
		}
	}
}

func TestEveryProviderRunsTheVendoredInstallerAndWritesIt(t *testing.T) {
	for _, provider := range []string{"github", "azure", "gitlab"} {
		cfg := workspace.Config{CI: workspace.CISection{Providers: []string{provider}}}
		assertVendored(t, provider, Rendered(cfg, model()))
	}
	cfg := workspace.Config{CI: workspace.CISection{Devcontainer: true}}
	assertVendored(t, "devcontainer", Rendered(cfg, model()))
	for name, out := range map[string]string{"github setup": GitHubSetup(model()), "azure setup": AzureSetup(model())} {
		if strings.Contains(out, "raw.githubusercontent.com") || !strings.Contains(out, "sh tools/smith/install.sh") {
			t.Errorf("%s:\n%s", name, out)
		}
	}
}

func assertVendored(t *testing.T, name string, files map[string]string) {
	t.Helper()
	if files[InstallScriptPath] != InstallScript() {
		t.Errorf("%s: %s not rendered", name, InstallScriptPath)
	}
	for path, out := range files {
		if path != InstallScriptPath && strings.Contains(out, "raw.githubusercontent.com") {
			t.Errorf("%s: %s still fetches from raw.githubusercontent.com", name, path)
		}
	}
}

func TestWriteVendorsTheInstallerAndDriftSeesItChange(t *testing.T) {
	root := t.TempDir()
	cfg := workspace.Config{CI: workspace.CISection{Providers: []string{"github"}}}
	if _, _, err := Write(root, cfg, model()); err != nil {
		t.Fatal(err)
	}
	full := filepath.Join(root, "tools", "smith", "install.sh")
	got, err := os.ReadFile(full)
	if err != nil || string(got) != InstallScript() {
		t.Fatalf("installer not written: %v", err)
	}
	if err := os.WriteFile(full, []byte("#!/bin/sh\necho old\n"), 0o755); err != nil {
		t.Fatal(err)
	}
	if drift := Drift(root, cfg, model()); len(drift) != 1 || !strings.Contains(drift[0], InstallScriptPath) {
		t.Fatalf("drift %v", drift)
	}
	planned, _ := Planned(root, cfg, model())
	if planned[InstallScriptPath] != InstallScript() || len(planned) != 1 {
		t.Fatalf("planned %v", planned)
	}
	_ = os.Remove(full)
	if drift := Drift(root, cfg, model()); len(drift) != 1 || !strings.Contains(drift[0], "missing") {
		t.Fatalf("drift %v", drift)
	}
}
