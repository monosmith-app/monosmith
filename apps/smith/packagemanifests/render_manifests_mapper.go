package packagemanifests

import (
	"encoding/json"
	"fmt"
	"strings"
	"unicode"
)

// Render writes the manifests asked for (homebrew, scoop, winget, aur, nix) as file
// name → content. A package manager whose platforms have no archive is
// skipped, with the reason in skipped.
func Render(r Release, managers []string) (files map[string]string, skipped []string) {
	files = map[string]string{}
	for _, m := range managers {
		var err error
		switch m {
		case "homebrew":
			err = homebrew(r, files)
		case "scoop":
			err = scoop(r, files)
		case "winget":
			err = winget(r, files)
		case "aur":
			err = aur(r, files)
		case "nix":
			err = nix(r, files)
		default:
			err = fmt.Errorf("unknown package manager")
		}
		if err != nil {
			skipped = append(skipped, m+": "+err.Error())
		}
	}
	return files, skipped
}

// className is a Ruby class name for the formula: my-tool → MyTool.
func className(product string) string {
	var b strings.Builder
	upper := true
	for _, c := range product {
		if !unicode.IsLetter(c) && !unicode.IsDigit(c) {
			upper = true
			continue
		}
		if upper {
			c = unicode.ToUpper(c)
			upper = false
		}
		b.WriteRune(c)
	}
	return b.String()
}

func homepage(r Release) string {
	if r.Homepage != "" {
		return r.Homepage
	}
	return "https://github.com/" + r.Owner + "/" + r.Repo
}

func homebrew(r Release, files map[string]string) error {
	var blocks []string
	for _, os := range []struct{ goos, block string }{{"darwin", "on_macos"}, {"linux", "on_linux"}} {
		var arches []string
		for _, a := range []struct{ goarch, block string }{{"arm64", "on_arm"}, {"amd64", "on_intel"}} {
			if archive, ok := r.find(os.goos, a.goarch); ok {
				arches = append(arches, fmt.Sprintf("    %s do\n      url %q\n      sha256 %q\n    end\n", a.block, r.URL(archive), archive.SHA256))
			}
		}
		if len(arches) > 0 {
			blocks = append(blocks, "  "+os.block+" do\n"+strings.Join(arches, "")+"  end\n")
		}
	}
	if len(blocks) == 0 {
		return fmt.Errorf("no macOS or Linux archive")
	}
	var b strings.Builder
	fmt.Fprintf(&b, "# Generated by smith for %s %s; copy it into your tap as Formula/%s.rb.\n", r.Product, r.Version, r.Product)
	fmt.Fprintf(&b, "class %s < Formula\n", className(r.Product))
	if r.Description != "" {
		fmt.Fprintf(&b, "  desc %q\n", r.Description)
	}
	fmt.Fprintf(&b, "  homepage %q\n  version %q\n", homepage(r), r.Version)
	if r.License != "" {
		fmt.Fprintf(&b, "  license %q\n", r.License)
	}
	b.WriteString("\n" + strings.Join(blocks, "\n"))
	fmt.Fprintf(&b, "\n  def install\n    bin.install %q\n  end\n\n  test do\n    system \"#{bin}/%s\", \"--version\"\n  end\nend\n", r.Binary, r.Binary)
	files[r.Product+".rb"] = b.String()
	return nil
}

func scoop(r Release, files map[string]string) error {
	arch := map[string]any{}
	for _, a := range []struct{ goarch, key string }{{"amd64", "64bit"}, {"arm64", "arm64"}} {
		if archive, ok := r.find("windows", a.goarch); ok {
			arch[a.key] = map[string]string{"url": r.URL(archive), "hash": archive.SHA256}
		}
	}
	if len(arch) == 0 {
		return fmt.Errorf("no Windows archive")
	}
	manifest := map[string]any{
		"version":      r.Version,
		"description":  r.Description,
		"homepage":     homepage(r),
		"license":      r.License,
		"architecture": arch,
		"bin":          r.Binary + ".exe",
	}
	raw, err := json.MarshalIndent(manifest, "", "    ")
	if err != nil {
		return err
	}
	files[r.Product+".json"] = string(raw) + "\n"
	return nil
}

func winget(r Release, files map[string]string) error {
	var installers strings.Builder
	for _, a := range []struct{ goarch, arch string }{{"amd64", "x64"}, {"arm64", "arm64"}} {
		if archive, ok := r.find("windows", a.goarch); ok {
			fmt.Fprintf(&installers, "  - Architecture: %s\n    InstallerUrl: %s\n    InstallerSha256: %s\n", a.arch, r.URL(archive), strings.ToUpper(archive.SHA256))
		}
	}
	if installers.Len() == 0 {
		return fmt.Errorf("no Windows archive")
	}
	id := r.Owner + "." + r.Product
	head := func(kind string) string {
		return fmt.Sprintf("# Generated by smith; submit it to microsoft/winget-pkgs under manifests/%s/%s/%s/%s.\n# yaml-language-server: $schema=https://aka.ms/winget-manifest.%s.1.6.0.schema.json\n\nPackageIdentifier: %s\nPackageVersion: %s\n",
			strings.ToLower(r.Owner[:1]), r.Owner, r.Product, r.Version, kind, id, r.Version)
	}
	files[id+".yaml"] = head("version") + "DefaultLocale: en-US\nManifestType: version\nManifestVersion: 1.6.0\n"
	files[id+".installer.yaml"] = head("installer") + fmt.Sprintf(
		"InstallerType: zip\nNestedInstallerType: portable\nNestedInstallerFiles:\n  - RelativeFilePath: %s.exe\n    PortableCommandAlias: %s\nInstallers:\n%sManifestType: installer\nManifestVersion: 1.6.0\n",
		r.Binary, r.Binary, installers.String())
	description := r.Description
	if description == "" {
		description = r.Product
	}
	license := r.License
	if license == "" {
		license = "Proprietary"
	}
	files[id+".locale.en-US.yaml"] = head("defaultLocale") + fmt.Sprintf(
		"PackageLocale: en-US\nPublisher: %s\nPackageName: %s\nPackageUrl: %s\nLicense: %s\nShortDescription: %s\nManifestType: defaultLocale\nManifestVersion: 1.6.0\n",
		r.Owner, r.Product, homepage(r), license, description)
	return nil
}
