package packagemanifests

import (
	"fmt"
	"strings"
)

// aur writes the PKGBUILD and .SRCINFO of an Arch User Repository "-bin"
// package that installs the binary from the Linux archives.
func aur(r Release, files map[string]string) error {
	type source struct{ arch, url, sum string }
	var sources []source
	for _, a := range []struct{ goarch, arch string }{{"amd64", "x86_64"}, {"arm64", "aarch64"}} {
		if archive, ok := r.find("linux", a.goarch); ok {
			sources = append(sources, source{a.arch, r.URL(archive), archive.SHA256})
		}
	}
	if len(sources) == 0 {
		return fmt.Errorf("no Linux archive")
	}
	pkgname := r.Product + "-bin"
	pkgver := strings.ReplaceAll(r.Version, "-", "_") // a pkgver has no hyphen
	desc := r.Description
	if desc == "" {
		desc = r.Product
	}
	license := r.License
	if license == "" {
		license = "custom"
	}
	var arches []string
	for _, s := range sources {
		arches = append(arches, "'"+s.arch+"'")
	}

	var p strings.Builder
	fmt.Fprintf(&p, "# Generated by smith for %s %s; copy it into the AUR repository of %s as PKGBUILD.\n", r.Product, r.Version, pkgname)
	fmt.Fprintf(&p, "pkgname=%s\npkgver=%s\npkgrel=1\npkgdesc=%s\narch=(%s)\nurl=%s\nlicense=(%s)\nprovides=(%s)\nconflicts=(%s)\n",
		pkgname, pkgver, shellQuote(desc), strings.Join(arches, " "), shellQuote(homepage(r)), shellQuote(license), shellQuote(r.Product), shellQuote(r.Product))
	for _, s := range sources {
		fmt.Fprintf(&p, "source_%s=(%s)\nsha256sums_%s=('%s')\n", s.arch, shellQuote(s.url), s.arch, s.sum)
	}
	fmt.Fprintf(&p, "\npackage() {\n  install -Dm755 \"$srcdir/%s\" \"$pkgdir/usr/bin/%s\"\n}\n", r.Binary, r.Binary)
	files[pkgname+".PKGBUILD"] = p.String()

	var i strings.Builder
	fmt.Fprintf(&i, "pkgbase = %s\n\tpkgdesc = %s\n\tpkgver = %s\n\tpkgrel = 1\n\turl = %s\n", pkgname, desc, pkgver, homepage(r))
	for _, s := range sources {
		fmt.Fprintf(&i, "\tarch = %s\n", s.arch)
	}
	fmt.Fprintf(&i, "\tlicense = %s\n\tprovides = %s\n\tconflicts = %s\n", license, r.Product, r.Product)
	for _, s := range sources {
		fmt.Fprintf(&i, "\tsource_%s = %s\n\tsha256sums_%s = %s\n", s.arch, s.url, s.arch, s.sum)
	}
	fmt.Fprintf(&i, "\npkgname = %s\n", pkgname)
	files[pkgname+".SRCINFO"] = i.String()
	return nil
}

func shellQuote(s string) string {
	return "'" + strings.ReplaceAll(s, "'", `'\''`) + "'"
}
