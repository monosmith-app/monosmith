package packagemanifests

import (
	"fmt"
	"strings"
)

// nix writes a flake.nix that installs the binary from the release archives,
// so `nix run` and `nix profile install` work from a repository that holds it.
func nix(r Release, files map[string]string) error {
	var entries []string
	for _, p := range []struct{ goos, goarch, system string }{
		{"linux", "amd64", "x86_64-linux"}, {"linux", "arm64", "aarch64-linux"},
		{"darwin", "amd64", "x86_64-darwin"}, {"darwin", "arm64", "aarch64-darwin"},
	} {
		if archive, ok := r.find(p.goos, p.goarch); ok {
			entries = append(entries, fmt.Sprintf("      %s = { url = %q; sha256 = %q; };\n", p.system, r.URL(archive), archive.SHA256))
		}
	}
	if len(entries) == 0 {
		return fmt.Errorf("no macOS or Linux archive")
	}
	desc := r.Description
	if desc == "" {
		desc = r.Product
	}
	var b strings.Builder
	fmt.Fprintf(&b, "# Generated by smith for %s %s; commit it as flake.nix in your repository.\n", r.Product, r.Version)
	fmt.Fprintf(&b, "{\n  description = %q;\n\n  inputs.nixpkgs.url = \"github:NixOS/nixpkgs/nixpkgs-unstable\";\n\n", desc)
	b.WriteString("  outputs = { self, nixpkgs }:\n    let\n      sources = {\n")
	b.WriteString(strings.Join(entries, ""))
	b.WriteString("      };\n      forSystems = nixpkgs.lib.genAttrs (builtins.attrNames sources);\n    in {\n")
	fmt.Fprintf(&b, "      packages = forSystems (system:\n        let\n          pkgs = nixpkgs.legacyPackages.${system};\n          src = pkgs.fetchurl sources.${system};\n        in {\n          default = pkgs.stdenvNoCC.mkDerivation {\n            pname = %q;\n            version = %q;\n            inherit src;\n            nativeBuildInputs = [ pkgs.unzip ];\n            sourceRoot = \".\";\n            installPhase = ''\n              install -Dm755 %s $out/bin/%s\n            '';\n            meta = {\n              description = %q;\n              homepage = %q;\n              mainProgram = %q;\n            };\n          };\n        });\n\n", r.Product, r.Version, r.Binary, r.Binary, desc, homepage(r), r.Binary)
	b.WriteString("      apps = forSystems (system: {\n        default = {\n          type = \"app\";\n          program = \"${self.packages.${system}.default}/bin/" + r.Binary + "\";\n        };\n      });\n    };\n}\n")
	files[r.Product+".flake.nix"] = b.String()
	return nil
}
