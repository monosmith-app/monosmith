package corefixes

import (
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"github.com/monosmith-app/monosmith/packages/plugin-sdk/protocol"
)

// UntrackDescription names the fix.
const UntrackDescription = "stop tracking the generated files"

// untrackChunk is how many paths one `git rm` step takes, so a long list fits
// the command line of every OS.
const untrackChunk = 100

// TrackedFile is a file git tracks that a run rewrites.
type TrackedFile struct {
	Path string
	// Ignored is true when .gitignore already ignores it (it was committed
	// before the rule).
	Ignored bool
	// OutputDir is the declared output directory it is inside, workspace
	// relative, when it is not ignored: the directory to ignore.
	OutputDir string
}

// UntrackFix stops tracking the files (`git rm --cached`: they stay on disk,
// the removal is staged for the user's commit). When some sit in an output
// directory .gitignore does not cover, the fix asks whether to ignore that
// directory too. It is not safe: it changes what the repository tracks.
func UntrackFix(root string, files []TrackedFile) *protocol.Fix {
	if len(files) == 0 {
		return nil
	}
	var paths []string
	dirs := map[string]bool{}
	for _, f := range files {
		if !f.Ignored && f.OutputDir != "" {
			dirs[f.OutputDir] = true
			continue
		}
		paths = append(paths, f.Path)
	}
	// A directory is removed as a whole; its files need no step of their own.
	remove := sortedKeys(dirs)
	for _, p := range paths {
		covered := false
		for _, d := range remove {
			covered = covered || p == d || strings.HasPrefix(p, d+"/")
		}
		if !covered {
			remove = append(remove, p)
		}
	}
	sort.Strings(remove)
	fix := &protocol.Fix{Description: UntrackDescription}
	for start := 0; start < len(remove); start += untrackChunk {
		end := min(start+untrackChunk, len(remove))
		fix.Steps = append(fix.Steps, protocol.FixStep{
			Description: fmt.Sprintf("stop tracking %d path(s); the files stay on disk and the removal is staged", end-start),
			Argv:        append([]string{"git", "rm", "-r", "--cached", "--ignore-unmatch", "--quiet", "--"}, remove[start:end]...),
		})
	}
	if len(dirs) > 0 {
		rules := make([]string, 0, len(dirs))
		for _, d := range sortedKeys(dirs) {
			rules = append(rules, "/"+d+"/")
		}
		existing, _ := os.ReadFile(filepath.Join(root, ".gitignore"))
		text := string(existing)
		if text != "" && !strings.HasSuffix(text, "\n") {
			text += "\n"
		}
		withRules := protocol.Fix{Files: []protocol.FileEdit{{Path: ".gitignore", Content: text + "\n# generated by builds\n" + strings.Join(rules, "\n") + "\n"}}}
		fix.Choices = []protocol.FixChoice{{
			Question: "These tracked files are task outputs that .gitignore does not cover. Ignore them from now on?",
			Options: []protocol.FixChoiceOption{
				{Label: "stop tracking and add " + strings.Join(rules, ", ") + " to .gitignore", Fix: withRules},
				{Label: "only stop tracking (a task may keep rewriting them on purpose)", Fix: protocol.Fix{}},
			},
		}}
	}
	return fix
}

func sortedKeys(m map[string]bool) []string {
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	return keys
}
