package adoptdecision

// The answers about .gitattributes.
const (
	// GitattributesAdd writes `* text=auto eol=lf` and binary rules.
	GitattributesAdd = "add"
	// GitattributesSkip leaves the repository's line endings as they are.
	GitattributesSkip = "skip"
)

// The answers about the agent files.
const (
	// AgentAdd writes the agent file and merges the MCP servers into .mcp.json.
	AgentAdd = "add"
	// AgentSkip writes nothing now; smith agent install adds the files later.
	AgentSkip = "skip"
	// AgentNever writes nothing and records [agent] enabled = false.
	AgentNever = "never"
)

// The answers about a pipeline the repository already has.
const (
	// ExistingReplace writes smith's pipeline and keeps yours as <file>.pre-smith.
	ExistingReplace = "replace"
	// ExistingKeep keeps yours in place and writes no pipeline for that provider.
	ExistingKeep = "keep"
)

// NoCI is the --ci value for "write no pipeline".
const NoCI = "none"

// Choices are the settled answers.
type Choices struct {
	// Gitattributes is GitattributesAdd or GitattributesSkip.
	Gitattributes string
	// Agent is AgentAdd, AgentSkip or AgentNever.
	Agent string
	// CI are the providers smith writes pipelines for; empty is none.
	CI []string
	// Existing is ExistingReplace or ExistingKeep, for the providers in CI.
	Existing string
}

// Flags are the answers given on the command line; "" and nil mean not given.
type Flags struct {
	Gitattributes string
	Agent         string
	// CI is --ci; CIGiven is true when the flag was passed (so "none" is an answer).
	CI       []string
	CIGiven  bool
	Existing string
}

// Facts are what the repository holds, which shapes the questions.
type Facts struct {
	// GitattributesExists is true when the repository has a .gitattributes: its
	// setting is used and the question is not asked.
	GitattributesExists bool
	// MCPExists is true when .mcp.json exists, so adding the agent merges into it.
	MCPExists bool
	// Detected are the CI providers the repository already uses, in order.
	Detected []string
	// OwnPipelines maps a provider to the path of a pipeline of the team's own
	// (not generated by smith), for the providers that have one.
	OwnPipelines map[string]string
}
