//go:build e2e

package goldenpath

import (
	"os"
	"path/filepath"
	"strings"
	"testing"
)

// TestAdoptRepository brings a plain Go repository under smith: a report of
// what adopting involves, then the steps: a baseline tag for a project
// tagged under its old name, and smith.toml and the pipelines, with the
// repository's own pipeline kept beside them.
func TestAdoptRepository(t *testing.T) {
	base := t.TempDir()
	w := &workspace{t: t, bin: buildSmith(t, base), dir: filepath.Join(base, "Legacy_Repo"), env: identity()}
	_ = os.MkdirAll(w.dir, 0o755)
	w.git("init", "-q", "-b", "main")
	w.write("go.work", "go 1.26\n\nuse ./libs/core\n")
	w.write("libs/core/go.mod", "// smith:kind package\nmodule example.com/legacy/libs/core\n\ngo 1.26\n")
	w.write("libs/core/core.go", "// Package core is the legacy core.\npackage core\n")
	w.write(".github/workflows/ci.yml", "name: theirs\non: push\njobs: {}\n")
	w.git("add", "-A")
	w.git("commit", "-qm", "feat: the legacy core")
	w.git("tag", "core@1.2.0")

	out := w.smith(false, "adopt")
	for _, want := range []string{`would be workspace "legacy-repo"`, "core", "libs/core", "--tags creates libs/core/v1.2.0", ".github/workflows/ci.yml is yours"} {
		if !strings.Contains(out, want) {
			t.Fatalf("adopt lacks %q:\n%s", want, out)
		}
	}
	w.write("scratch.txt", "work in progress\n")
	if out := w.smith(false, "adopt", "--tags"); !strings.Contains(out, "commit or stash your changes first") {
		t.Fatalf("a dirty tree must stop the steps:\n%s", out)
	}
	_ = os.Remove(filepath.Join(w.dir, "scratch.txt"))

	out = w.smith(true, "adopt", "--tags", "--init")
	if !strings.Contains(out, "tagged libs/core/v1.2.0") || !strings.Contains(out, "✓ adopted") {
		t.Fatalf("adopt --tags --init:\n%s", out)
	}
	if commit := strings.TrimSpace(w.git("rev-parse", "libs/core/v1.2.0^{commit}")); commit != strings.TrimSpace(w.git("rev-parse", "core@1.2.0^{commit}")) {
		t.Fatal("the baseline tag must be on the old tag's commit")
	}
	if !strings.Contains(w.read(".github/workflows/ci.yml.pre-smith"), "name: theirs") || !strings.Contains(w.read(".github/workflows/ci.yml"), "Generated by smith") {
		t.Fatal("their pipeline is kept beside smith's")
	}
	if cfg := w.read("smith.toml"); !strings.Contains(cfg, `name = "legacy-repo"`) || !strings.HasPrefix(cfg, "#:schema") {
		t.Fatalf("smith.toml:\n%s", cfg)
	}
	if !strings.Contains(w.read(".gitignore"), ".smith/") {
		t.Fatal(".smith/ must be ignored")
	}
	if subject := strings.TrimSpace(w.git("log", "-1", "--format=%s")); subject != "chore: adopt smith" {
		t.Fatalf("last commit %q", subject)
	}
	if status := strings.TrimSpace(w.git("status", "--porcelain")); status != "" {
		t.Fatalf("adopt leaves nothing uncommitted:\n%s", status)
	}
	// The next release starts from the version the old tag carried.
	w.write("libs/core/core.go", "// Package core is the legacy core.\npackage core\n\n// Answer is new.\nconst Answer = 42\n")
	w.git("add", "-A")
	w.git("commit", "-qm", "feat: an answer")
	if out := w.smith(true, "release", "--dry-run"); !strings.Contains(out, "1.3.0") || strings.Contains(out, "blocked") {
		t.Fatalf("release after adopting:\n%s", out)
	}
	if out := w.smith(false, "adopt"); !strings.Contains(out, "already a smith workspace") {
		t.Fatalf("adopting twice:\n%s", out)
	}
}
