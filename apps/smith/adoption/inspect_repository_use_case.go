// GeneratedMarker starts every file smith owns.
const GeneratedMarker = "Generated by smith"

var unsafeName = regexp.MustCompile(`[^a-z0-9]+`)

// Inspect reads the repository at dir and reports what adopting it involves.
// It changes nothing.
func Inspect(dir, version string, log io.Writer) (Report, error) {
	root, err := filepath.Abs(dir)
	if err != nil {
		return Report{}, err
	}
	r := Report{Root: root, Name: workspaceName(root)}
	exists := func(rel string) bool {
		_, err := os.Stat(filepath.Join(root, filepath.FromSlash(rel)))
		return err == nil
	}
	git := gitclient.New(root)
	switch {
	case !git.IsRepository():
		r.Blockers = append(r.Blockers, Item{Message: "this is not a git repository: smith versions from tags and finds files through git", Step: "git init, then commit what you have", Blocks: BlocksAdoption})
		return r, nil
	case exists(workspace.FileName):
		r.Blockers = append(r.Blockers, Item{Message: "this is already a smith workspace", Step: "nothing to adopt: smith doctor checks it, smith upgrade brings it up to this smith", Blocks: BlocksAdoption})
		return r, nil
	case exists("turbo.json") && !exists("nx.json"):
		r.Blockers = append(r.Blockers, Item{Message: "this is a Turborepo workspace: its tasks are turbo.json's to describe", Step: "smith convert --dry-run", Blocks: BlocksAdoption})
		return r, nil
	case exists("nx.json"):
		item := Item{Message: "this is an Nx workspace: its projects and targets are Nx's to describe", Step: "smith convert --dry-run", Blocks: BlocksAdoption}
		if !exists("node_modules/nx") {
			item.Steps = []string{"npm ci, so Nx can describe the projects", "then smith convert --dry-run"}
			item.Step = item.Steps[0]
		}
		r.Blockers = append(r.Blockers, item)
		return r, nil
	}
	status, _ := git.Run("status", "--porcelain")
	r.Clean = cleanApartFromSmith(status)
	r.Scope = scopeOf(root, r.Name)
	r.Providers = providersOf(exists)
	files, _ := git.Files()
	read := func(rel string) string {
		raw, _ := os.ReadFile(filepath.Join(root, filepath.FromSlash(rel)))
		return string(raw)
	}
	if item, ok := PnpmWorkspace(files, read); ok {
		r.Blockers = append(r.Blockers, item)
		return r, nil
	}

	if exists("go.mod") {
		var rootProgram bool
		r.Declared, rootProgram = InferGoProjects(root)
		if rootProgram {
			r.Warnings = append(r.Warnings, Item{Message: "the root module's main package is in the repository's own folder, which cannot be a project", Step: "move it to cmd/<name> (git mv main.go cmd/<name>/main.go), commit, then run smith adopt again"})
		}
	}
	cfg, err := previewConfig(r)
	if err != nil {
		return r, err
	}
	s, err := session.Open(session.Options{Dir: root, Version: version, Log: log, Preview: &cfg})
	if err != nil {
		return r, err
	}
	defer s.Close()
	for _, p := range s.Graph.Projects {
		r.Projects = append(r.Projects, ProjectLine{Name: p.Name, Root: p.Root, Language: p.Language, Kind: string(p.Kind), Stack: p.Stack})
	}
	sort.Slice(r.Projects, func(i, j int) bool { return r.Projects[i].Root < r.Projects[j].Root })
	if len(r.Projects) == 0 {
		r.Warnings = append(r.Warnings, noProjectWarning(exists))
	}
	for _, f := range release.CheckLineage(s, false) {
		item := Item{Message: f.Message, Baseline: f.Baseline, Steps: f.Remedy}
		if f.Baseline != nil {
			// --tags makes the tag the first remedy describes.
			item.Steps = append([]string{"smith adopt --tags creates " + f.Baseline.Name + " on " + strings.TrimSuffix(f.Baseline.Target, "^{commit}") + " (locally; push it yourself)"}, f.Remedy[min(1, len(f.Remedy)):]...)
		}
		if len(item.Steps) == 0 {
			item.Steps = []string{"smith doctor repeats this once the workspace exists"}
		}
		item.Step = item.Steps[0]
		if f.Blocking {
			item.Blocks = BlocksRelease
			r.Blockers = append(r.Blockers, item)
		} else {
			r.Warnings = append(r.Warnings, item)
		}
	}
	for _, f := range doctor.PluginChecks(s, nil) {
		if f.OK || f.Warning {
			continue
		}
		r.Warnings = append(r.Warnings, predictedFailure(f))
	}
	for _, path := range []string{cipipeline.GitHubPath, cipipeline.AzurePath, cipipeline.DevcontainerPath} {
		body, err := os.ReadFile(filepath.Join(root, filepath.FromSlash(path)))
		if err == nil && !strings.Contains(string(body), GeneratedMarker) {
			r.Warnings = append(r.Warnings, Item{Message: path + " is yours, at a path smith's pipeline uses", Step: "--init keeps it as " + path + ".pre-smith; move your own steps into the generated file's slots"})
		}
	}
	r.Warnings = append(r.Warnings, ExistingWorkflows(files, read, r.Providers)...)
	if deps := rootRuntimeDependencies(root); len(deps) > 0 && hasNodeProjects(r.Projects) {
		r.Warnings = append(r.Warnings, Item{Message: "the root package.json has runtime dependencies (" + strings.Join(deps, ", ") + "): in smith each project declares what it uses", Step: "smith install -w <project> <package> for each project that imports it, then drop it from the root"})
	}
	return r, nil
}

// noProjectWarning explains an empty project list. A package.json at the root
// is the commonest cause: smith's projects live in apps/, libs/ or packages/,
// and the root manifest describes the workspace, not a project.
func noProjectWarning(exists func(string) bool) Item {
	if exists("package.json") {
		return Item{
			Message: "no project found: the package.json at the root describes the workspace, not a project, and smith looks for projects in their own folders (apps/, libs/ or packages/)",
			Steps: []string{
				"move the code into packages/<name> (git mv src packages/<name>/src, and its package.json), commit, then run smith adopt again",
				"or run smith adopt --init now and add projects with smith add app <name> --lang <language>",
			},
		}
	}
	if exists("go.mod") {
		return Item{
			Message: "no project found: the go.mod at the root is one module for the whole repository, and smith runs a Go project from a go.mod in its own folder (one module per project, joined by a go.work)",
			Steps: []string{
				"give each program or library its own go.mod (go mod init <module>/apps/<name> in its folder), list them in a go.work at the root (go work init; go work use ./apps/<name> ...), make the programs require the libraries, commit, then run smith adopt again",
				"or run smith adopt --init now and add projects with smith add app <name> --lang go",
			},
		}
	}
	return Item{
		Message: "no project found: smith knows a project by its manifest (package.json in a workspace, go.mod, pyproject.toml)",
		Steps:   []string{"smith adopt --init makes an empty workspace; then smith add app <name> --lang <language>"},
	}
}

// workspaceName is the directory's name made a valid workspace name.
func workspaceName(root string) string {
	name := strings.Trim(unsafeName.ReplaceAllString(strings.ToLower(filepath.Base(root)), "-"), "-")
	if name == "" || name[0] < 'a' || name[0] > 'z' {
		name = "workspace-" + name
	}
	return strings.TrimSuffix(name, "-")
}

// scopeOf is the npm scope the root package.json's name uses, else the
// workspace name's.
func scopeOf(root, name string) string {
	var pkg struct{ Name string }
	if raw, err := os.ReadFile(filepath.Join(root, "package.json")); err == nil && json.Unmarshal(raw, &pkg) == nil && strings.HasPrefix(pkg.Name, "@") {
		return strings.SplitN(pkg.Name, "/", 2)[0]
	}
	return "@" + name
}

// providersOf keeps the CI providers the repository already uses.
func providersOf(exists func(string) bool) []string {
	var out []string
	if exists(".github/workflows") {
		out = append(out, "github")
	}
	if exists(cipipeline.AzurePath) {
		out = append(out, "azure")
	}
	if len(out) == 0 {
		out = []string{"github"}
	}
	return out
}

func previewConfig(r Report) (workspace.Config, error) {
	quoted := make([]string, len(r.Providers))
	for i, p := range r.Providers {
		quoted[i] = fmt.Sprintf("%q", p)
	}
	text := fmt.Sprintf("schema = %d\n\n[workspace]\nname = %q\nscope = %q\n\n[ci]\nproviders = [%s]\n", workspace.SchemaVersion, r.Name, r.Scope, strings.Join(quoted, ", "))
	return workspace.Parse([]byte(text + declarationsText(r.Declared)))
}

func rootRuntimeDependencies(root string) []string {
	var pkg struct{ Dependencies map[string]string }
	raw, err := os.ReadFile(filepath.Join(root, "package.json"))
	if err != nil || json.Unmarshal(raw, &pkg) != nil {
		return nil
	}
	var out []string
	for name := range pkg.Dependencies {
		out = append(out, name)
	}
	sort.Strings(out)
	return out
}

func hasNodeProjects(projects []ProjectLine) bool {
	for _, p := range projects {
		if p.Language == "node" {
			return true
		}
	}
	return false
}

// predictedFailure is a check smith doctor will fail on once the workspace
// exists, said now. The mechanical ones are done by --init (npm install by
// --install); the others are the plugin's own remedy.
func predictedFailure(f doctor.Finding) Item {
	item := Item{Message: "smith doctor will report: " + f.Detail}
	switch {
	case f.Check == "go.work exists":
		item.Steps = []string{"--init runs go work init and go work use for you"}
	case strings.HasPrefix(f.Check, "npm workspaces include "):
		item.Steps = []string{"--init adds the \"workspaces\" to the root package.json for you"}
	case f.Check == "Node dependencies are installed":
		item.Steps = []string{"--init --install runs npm install for you (or run it yourself afterwards)"}
	default:
		lines := strings.Split(f.Remedy, "\n")
		item.Steps = []string{lines[0]}
		if len(lines) > 1 {
			item.Steps[0] += " (smith doctor shows the rest)"
		}
	}
	item.Step = item.Steps[0]
	return item
}

// cleanApartFromSmith says whether git status (--porcelain) lists nothing but
// what smith itself leaves in the working tree: the .smith folder, which holds
// the cache and the default tool configurations it derives and never commits. A
// dry run that wrote them must not make the repository look changed.
func cleanApartFromSmith(status string) bool {
	for _, line := range strings.Split(status, "\n") {
		line = strings.TrimSpace(line)
		if line == "" {
			continue
		}
		if f := strings.Fields(line); len(f) == 2 && (f[1] == ".smith/" || strings.HasPrefix(f[1], ".smith/")) {
			continue
		}
		return false
	}
	return true
}
