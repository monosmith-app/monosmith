// How the schema's names are spelled in C#.

/** A schema word as a C# identifier part: `dependsOn` and `applies_to` become `DependsOn` and `AppliesTo`. */
export function pascal(name) {
  return name
    .split(/[_\-/\s]+/)
    .filter((part) => part !== '')
    .map((part) => part[0].toUpperCase() + part.slice(1))
    .join('')
}

/** A parameter name: the first letter lower case. */
export function camel(name) {
  const text = pascal(name)
  return text[0].toLowerCase() + text.slice(1)
}

// The schema's `Task` is the one name the BCL's `System.Threading.Tasks.Task` (imported by every file) would hide.
const RENAMED = { Task: 'ProjectTask' }

/** The C# name of a definition of the schema. */
export function typeName(definition) {
  return RENAMED[definition] ?? definition
}

/** The C# string literal of a text. */
export function literal(text) {
  return `"${text.replaceAll('\\', '\\\\').replaceAll('"', '\\"').replaceAll('\n', '\\n')}"`
}

