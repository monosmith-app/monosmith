"""Maps the protocol JSON Schema to the Python module that carries it as data."""

from __future__ import annotations

import json
from typing import Any

HEADER = '''"""The JSON Schema of the plugin protocol, as data.

GENERATED by tools/generate_protocol from packages/plugin-sdk/schema/protocol.schema.json.
Do not edit it. The wire codec and the host's capability check read it at run time.
"""
# ruff: noqa: E501, N815
from __future__ import annotations

import json
from typing import Any, Final

__all__ = ["PROTOCOL_SCHEMA"]
'''


def map_schema_to_module(schema: dict[str, Any]) -> str:
    """The Python source of `protocol_schema_contract.py`: the schema itself, parsed once at import."""
    text = json.dumps(schema, indent=2, ensure_ascii=False)
    if "'''" in text:
        raise ValueError("the schema contains a triple quote: extend the generator")
    return (
        HEADER
        + "\n_SCHEMA_JSON = r'''"
        + text
        + "'''\n\n"
        + "PROTOCOL_SCHEMA: Final[dict[str, Any]] = json.loads(_SCHEMA_JSON)\n"
        + '"""The JSON Schema of the plugin protocol, as committed in packages/plugin-sdk/schema."""\n'
    )
