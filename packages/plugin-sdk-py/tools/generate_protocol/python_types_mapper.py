"""Maps the protocol JSON Schema to the Python source of the SDK's protocol types."""

from __future__ import annotations

import json
import keyword
import re
from typing import Any

from .docstring_text_algorithm import docstring

SchemaNode = dict[str, Any]

REF_PREFIX = "#/$defs/"
SCALARS = {"string": "str", "integer": "int", "number": "float", "boolean": "bool", "null": "None"}
IDENTIFIER = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")

HEADER = '''"""The messages of the smith plugin protocol, as types.

GENERATED by tools/generate_protocol from packages/plugin-sdk/schema/protocol.schema.json.
Do not edit it: change the Go types in packages/plugin-sdk/protocol, regenerate the schema
(`smith run schema -p plugin-sdk`), then run `smith run generate -p plugin-sdk-py`.

Every message is a `TypedDict`: the JSON object as a plain `dict`, so a plugin returns
`{"projects": [...]}` and a type checker knows the members. A member that the Go SDK writes
without `omitempty` is required; every other is optional and may be left out. Enumerations
are `Literal` aliases and are not validated at run time: a value the schema does not list
(a newer host's) passes through.
"""
# ruff: noqa: E501, N815
from __future__ import annotations

from typing import Any, Final, Literal, TypedDict
'''


def type_of(node: SchemaNode) -> str:
    """The Python annotation of a schema node."""
    ref = node.get("$ref")
    if ref is not None:
        return str(ref)[len(REF_PREFIX) :]
    branches = node.get("anyOf")
    if branches is not None:
        return " | ".join(type_of(branch) for branch in branches)
    kind = node.get("type")
    if isinstance(kind, list):
        return " | ".join(type_of({"type": t}) for t in kind)
    if kind == "array":
        return f"list[{type_of(node.get('items') or {})}]"
    if kind == "object":
        values = node.get("additionalProperties")
        return f"dict[str, {type_of(values) if isinstance(values, dict) else 'Any'}]"
    return SCALARS.get(kind, "Any") if kind is not None else "Any"


def _member(name: str, owner: str, node: SchemaNode) -> str:
    if not IDENTIFIER.match(name) or keyword.iskeyword(name):
        raise ValueError(f"member {name!r} of {owner} cannot be a TypedDict member: extend the generator")
    return f"    {name}: {type_of(node)}\n{docstring(node.get('description'), '    ')}"


def _class(name: str, bases: str, node: SchemaNode, members: list[tuple[str, SchemaNode]], doc: bool) -> str:
    body = "".join(_member(member, name, spec) for member, spec in members)
    head = f"class {name}({bases}):\n"
    text = docstring(node.get("description"), "    ") if doc else ""
    if not text and not body:
        body = "    pass\n"
    return head + text + ("\n" if text and body else "") + body


def declaration(name: str, node: SchemaNode) -> str:
    """One definition of the schema as a `Literal` alias or a `TypedDict`."""
    if "enum" in node:
        members = ", ".join(json.dumps(value) for value in node["enum"])
        one_line = f"{name} = Literal[{members}]\n"
        if len(one_line) > 100:
            members = "".join(f"    {json.dumps(value)},\n" for value in node["enum"])
            one_line = f"{name} = Literal[\n{members}]\n"
        return one_line + docstring(node.get("description"))
    properties: dict[str, SchemaNode] = node.get("properties") or {}
    if node.get("type") != "object" or (not properties and name != "Empty"):
        return f"{name} = {type_of(node)}\n{docstring(node.get('description'))}"
    required = set(node.get("required") or [])
    needed = [(m, spec) for m, spec in properties.items() if m in required]
    optional = [(m, spec) for m, spec in properties.items() if m not in required]
    if needed and optional:
        base = f"_{name}Required"
        return (
            _class(base, "TypedDict", node, needed, False)
            + "\n\n"
            + _class(name, f"{base}, total=False", node, optional, True)
        )
    if optional:
        return _class(name, "TypedDict, total=False", node, optional, True)
    return _class(name, "TypedDict", node, needed, True)


def _constant_name(name: str) -> str:
    return re.sub(r"(?<!^)(?=[A-Z])", "_", name).upper()


def _error_codes(schema: dict[str, Any]) -> str:
    rows = "".join(
        f"    {_constant_name(row['name'])}: Final = {row['code']}\n{docstring(row.get('description'), '    ')}\n"
        for row in schema["x-errorCodes"]
    )
    summary = (
        "The error codes of the protocol: the JSON-RPC 2.0 ones, PLUGIN_FAILURE for a failure the user "
        "must act on and REQUEST_CANCELLED for a cancelled request."
    )
    return f"class ErrorCodes:\n{docstring(summary, '    ')}\n{rows.rstrip()}\n"


DERIVED = {
    "PluginDescription": (
        "InitializeResult",
        ("protocolVersion", "capabilities"),
        "What a plugin says about itself: the `initialize` result without the members the serve loop "
        "fills in, `protocolVersion` and `capabilities` (derived from the methods the plugin has).",
    ),
}
"""Types the SDK adds to the schema's: a definition without some of its members."""


def derived_definitions(definitions: dict[str, SchemaNode]) -> dict[str, SchemaNode]:
    """The `DERIVED` types as schema nodes."""
    derived: dict[str, SchemaNode] = {}
    for name, (source, omitted, description) in DERIVED.items():
        node = definitions[source]
        derived[name] = {
            **node,
            "description": description,
            "properties": {m: spec for m, spec in node["properties"].items() if m not in omitted},
            "required": [m for m in node.get("required") or [] if m not in omitted],
        }
    return derived


def map_schema_to_types(schema: dict[str, Any]) -> str:
    """The Python source of `protocol_types_contract.py`: one type per definition of the schema,
    the error codes, the protocol version and the methods table's names as constants."""
    definitions: dict[str, SchemaNode] = schema["$defs"]
    derived = derived_definitions(definitions)
    methods: dict[str, SchemaNode] = schema["x-methods"]
    capabilities = list(definitions["Capabilities"]["properties"])
    names = [
        "PROTOCOL_VERSION",
        "MAX_MESSAGE_BYTES",
        "ERROR_CODES",
        "ErrorCodes",
        "MethodName",
        "CapabilityName",
        "METHOD_CAPABILITIES",
        *definitions,
        *derived,
    ]
    exported = "".join(f'    "{name}",\n' for name in names)
    capability_rows = "".join(
        f"    {json.dumps(method)}: {json.dumps(row['capability']) if row['capability'] else 'None'},\n"
        for method, row in methods.items()
    )
    parts = [
        HEADER + f"\n__all__ = [\n{exported}]\n",
        "PROTOCOL_VERSION: Final = " + str(schema["x-protocolVersion"]) + "\n"
        '"""The protocol major version this SDK speaks. A breaking change to the protocol raises it."""\n',
        f"MAX_MESSAGE_BYTES: Final = {schema['x-transport']['maxMessageBytes']}\n"
        '"""The largest message the framing accepts, in bytes."""\n',
        _error_codes(schema),
        "ERROR_CODES = ErrorCodes()\n",
        "MethodName = Literal[" + ", ".join(json.dumps(m) for m in methods) + "]\n"
        '"""Every method of the protocol, `initialize`, `shutdown` and the `cancel` notification too."""\n',
        "CapabilityName = Literal[" + ", ".join(json.dumps(c) for c in capabilities) + "]\n"
        '"""The names of the capability flags: the optional methods a plugin implements."""\n',
        "METHOD_CAPABILITIES: Final[dict[str, str | None]] = {\n" + capability_rows + "}\n"
        '"""The capability a plugin advertises to be asked each method (`None`: always available).\n\n'
        "Capability names are not method names: `version/write` is the `version` capability.\n"
        '"""\n',
        *(declaration(name, node) for name, node in {**definitions, **derived}.items()),
    ]
    return "\n\n".join(part.rstrip("\n") + "\n" for part in parts)
