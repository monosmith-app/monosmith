class _PluginDescriptionRequired(TypedDict):
    plugin: Peer
    kind: PluginKind


class PluginDescription(_PluginDescriptionRequired, total=False):
    """
    What a plugin says about itself: the `initialize` result without the members the serve loop
    fills in, `protocolVersion` and `capabilities` (derived from the methods the plugin has).
    """

    concurrency: int
    """
    Concurrency is how many requests the plugin can work on at the same time; the host never has
    more in flight. Absent or 0 means 1, which is what every plugin that says nothing does: the
    host sends the next request only after the previous one is answered. N above 1 allows that
    many, and ConcurrencyUnlimited (-1) leaves the number to the host. Any other negative value
    is invalid and read as 1.
    """
    languages: list[str]
    """Languages are the values a user passes to --lang to reach this plugin."""
    manifests: list[str]
    """
    Manifests are file base names (package.json, go.mod), or patterns of them (*.csproj), whose
    presence in a directory may make it a project of this plugin.
    """
    roles: list[Role]
    """
    Roles are the levels the plugin can be chosen for in a project's make-up (a stack, a recipe).
    Empty means the default of its kind (see DefaultRoles). A role is a level: there is no
    separate level field, because one plugin can play several (a scaffold that is also a
    toolchain).
    """
    provides: list[str]
    """
    Provides are the slots a toolchain plugin fills: the task names it owns ("test" for a test
    runner). A slot is exclusive: two plugins of one project may not provide the same task.
    """
    requires: list[PluginRef]
    """
    Requires are plugins that must also be in the project for this one to work: a Node toolchain
    requires the node language plugin.
    """
    conflicts: list[PluginRef]
    """Conflicts are plugins that must not be in the same project."""
    stacks: list[Stack]
    """Stacks are ready-made stacks the plugin publishes."""
    kinds: list[ProjectKind]
    """
    Kinds are the project kinds the plugin can scaffold with generate. Absent or empty means all
    three (app, lib and package): what every plugin that says nothing does. A plugin that
    scaffolds only some, such as an app, lists them, so the host offers and the conformance suite
    asks for just those.
    """
    follows: list[str]
    """
    Follows are the shape keys (see Project.Shape) the plugin applies when it generates a project
    with GenerateParams.Shape. Where siblings split on a key, the host asks the person only for a
    key that a plugin of the stack follows. Absent means the plugin follows none.
    """
    choices: list[Choice]
    """
    Choices are the options on an axis (framework, test, style) the plugin owns. The host lists
    them (smith choices) and checks a selection of them (smith add --with). Absent means the
    plugin owns none.
    """
