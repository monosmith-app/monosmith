class ErrorCodes:
    """
    The error codes of the protocol: the JSON-RPC 2.0 ones, PLUGIN_FAILURE for a failure the user
    must act on and REQUEST_CANCELLED for a cancelled request.
    """

    PARSE_ERROR: Final = -32700
    """The message was not valid JSON. The response has a null id."""

    INVALID_REQUEST: Final = -32600
    """
    The request is not valid, or arrived out of order: every request before initialize is refused
    with this code.
    """

    METHOD_NOT_FOUND: Final = -32601
    """
    The plugin does not implement the method, or did not advertise the capability. The message is
    "method not supported: <method>".
    """

    INVALID_PARAMS: Final = -32602
    """The params do not have the shape the method expects."""

    INTERNAL_ERROR: Final = -32603
    """
    The plugin failed in a way that is not the user's to act on, for example a result that could
    not be encoded.
    """

    PLUGIN_FAILURE: Final = -32000
    """
    The method ran and failed for a reason the user must act on (a missing toolchain, a bad
    manifest). The message is shown to the user as it is, so it should say what to do. An error a
    method of the Go SDK returns becomes this code.
    """

    REQUEST_CANCELLED: Final = -32800
    """
    The plugin stopped the request because the host sent a cancel notification for its id. A
    plugin that had finished answers with the result instead. Only a plugin that advertised the
    cancel capability sends it; when a cancelled request fails with any error, the SDKs answer
    with this code.
    """


