import type { SchemaDocument } from '../../src/protocol/schema-document.contract.ts'

/**
 * The TypeScript source of `src/protocol/protocol-schema.contract.ts`: the
 * schema itself as a constant, which the wire codec and the host's capability
 * check read at run time.
 */
export function mapSchemaToModule (schema: SchemaDocument): string {
  return '/* eslint-disable */\n// GENERATED by tools/generate-protocol from packages/plugin-sdk/schema/protocol.schema.json. Do not edit it.\n' +
    "import type { SchemaDocument } from './schema-document.contract.ts'\n\n" +
    '/** The JSON Schema of the plugin protocol, as committed in packages/plugin-sdk/schema. */\n' +
    `export const protocolSchema: SchemaDocument = ${JSON.stringify(schema, null, 2)}\n`
}
