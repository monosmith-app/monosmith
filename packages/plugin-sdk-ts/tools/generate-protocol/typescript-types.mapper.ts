import type { SchemaDocument, SchemaNode } from '../../src/protocol/schema-document.contract.ts'
import { jsdocComment } from './jsdoc-comment.algorithm.ts'

const IDENTIFIER = /^[A-Z_$][\w$]*$/i
const SCALARS: Readonly<Record<string, string>> = { string: 'string', integer: 'number', number: 'number', boolean: 'boolean', null: 'null' }

/** A member or method name as TypeScript writes it: bare when it can be, quoted when not. */
function key (name: string): string {
  return IDENTIFIER.test(name) ? name : `'${name}'`
}

function literal (value: string): string {
  return `'${value.replaceAll('\\', '\\\\').replaceAll("'", String.raw`\'`)}'`
}

/** The TypeScript type of a schema node. */
export function typeOf (node: SchemaNode): string {
  if (node.$ref !== undefined) return node.$ref.slice('#/$defs/'.length)
  if (node.anyOf !== undefined) return node.anyOf.map(branch => typeOf(branch)).join(' | ')
  const type = node.type
  if (Array.isArray(type)) return type.map(t => typeOf({ type: t })).join(' | ')
  if (type === 'array') return `${parenthesize(typeOf(node.items ?? {}))}[]`
  if (type === 'object') {
    const values = node.additionalProperties

    return `Record<string, ${typeof values === 'object' ? typeOf(values) : 'unknown'}>`
  }

  return (type !== undefined && SCALARS[type]) || 'unknown'
}

function parenthesize (type: string): string {
  return type.includes(' | ') ? `(${type})` : type
}

function declaration (name: string, node: SchemaNode): string {
  const doc = jsdocComment(node.description)
  if (node.enum !== undefined) {
    const members = node.enum.map(value => literal(value))
    const oneLine = `export type ${name} = ${members.join(' | ')}\n`

    return oneLine.length <= 100 ? `${doc}${oneLine}` : `${doc}export type ${name} =\n${members.map(m => `  | ${m}`).join('\n')}\n`
  }
  if (node.properties === undefined) {
    return `${doc}export type ${name} = ${name === 'Empty' ? 'Record<string, never>' : typeOf(node)}\n`
  }
  const required = new Set(node.required)
  const members = Object.entries(node.properties).map(([member, property]) =>
    `${jsdocComment(property.description, '  ')}  ${key(member)}${required.has(member) ? '' : '?'}: ${typeOf(property)}\n`)

  return `${doc}export interface ${name} {\n${members.join('')}}\n`
}

/**
 * The TypeScript source of `src/protocol/protocol-types.contract.ts`: one
 * type per definition of the schema, the methods table as a type, the error
 * codes and the protocol version as constants.
 */
export function mapSchemaToTypes (schema: SchemaDocument): string {
  const codes = schema['x-errorCodes'].map(row => `${jsdocComment(row.description, '  ')}  ${key(row.name)}: ${row.code},\n`)
  const rows = Object.entries(schema['x-methods']).map(([method, row]) =>
    `${jsdocComment(row.description, '  ')}  ${key(method)}: {\n    params: ${typeOf(row.params)}\n    result: ${row.result === null ? 'null' : typeOf(row.result)}\n` +
    `    capability: ${row.capability === null ? 'null' : literal(row.capability)}\n  }\n`)

  return [
    '/* eslint-disable */\n// GENERATED by tools/generate-protocol from packages/plugin-sdk/schema/protocol.schema.json.\n' +
    '// Do not edit it: change the Go types in packages/plugin-sdk/protocol, regenerate the schema\n' +
    '// (`smith run schema -p plugin-sdk`), then run `smith run generate -p plugin-sdk-ts`.\n',
    '/** The protocol major version this SDK speaks. A breaking change to the protocol raises it. */\n' +
    `export const PROTOCOL_VERSION = ${schema['x-protocolVersion']}\n`,
    '/** The largest message the framing accepts, in bytes. */\n' +
    `export const MAX_MESSAGE_BYTES = ${schema['x-transport'].maxMessageBytes}\n`,
    '/** The error codes of the protocol: the JSON-RPC 2.0 ones, and `PluginFailure` for a failure the user must act on. */\n' +
    `export const ERROR_CODES = {\n${codes.join('')}} as const\n`,
    'export type ErrorCode = (typeof ERROR_CODES)[keyof typeof ERROR_CODES]\n',
    ...Object.entries(schema.$defs).map(([name, node]) => declaration(name, node)),
    '/** Every method of the protocol with its params, its result and the capability a plugin advertises to be asked it. */\n' +
    `export interface ProtocolMethods {\n${rows.join('')}}\n`,
    'export type MethodName = keyof ProtocolMethods\n',
    "export type ParamsOf<M extends MethodName> = ProtocolMethods[M]['params']\n",
    "export type ResultOf<M extends MethodName> = ProtocolMethods[M]['result']\n",
    '/** The names of the capability flags: the optional methods a plugin implements. */\nexport type CapabilityName = keyof Capabilities\n',
  ].join('\n')
}
