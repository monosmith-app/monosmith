package registries

import (
	"bytes"
	"encoding/xml"
	"fmt"
	"strings"

	"github.com/monosmith-app/monosmith/packages/plugin-sdk/protocol"
)

// Marker is the comment that makes a nuget.config smith's: one with it is
// rewritten from smith.toml, one without it is the team's and left alone.
// XML forbids "--" inside a comment, so it does not spell the flag out.
const Marker = "<!-- Generated by smith from [registries] in smith.toml; smith doctor rewrites it. -->"

// NuGetOrg is nuget.org's service index.
const NuGetOrg = "https://api.nuget.org/v3/index.json"

// Config is the nuget.config for the feeds the workspace restores from and
// publishes to, or "" when none has a NuGet URL.
//   - Azure Artifacts: the feed alone (its upstream sources serve nuget.org);
//     NuGetAuthenticate@1 signs in in CI, the Azure Artifacts Credential
//     Provider on a laptop
//   - GitHub Packages and token feeds: the feed beside nuget.org, with the
//     token read from the environment (%GITHUB_TOKEN%, %<token_env>%)
func Config(r *protocol.Registries) string {
	if r == nil {
		return ""
	}
	var feeds []*protocol.Registry
	seen := map[string]bool{}
	for _, reg := range []*protocol.Registry{r.Install, r.Publish} {
		if reg != nil && reg.NuGet != "" && !seen[reg.Name] {
			seen[reg.Name] = true
			feeds = append(feeds, reg)
		}
	}
	if len(feeds) == 0 {
		return ""
	}
	var b strings.Builder
	b.WriteString("<?xml version=\"1.0\" encoding=\"utf-8\"?>\n" + Marker + "\n<configuration>\n  <packageSources>\n    <clear />\n")
	onlyAzure := true
	for _, f := range feeds {
		fmt.Fprintf(&b, "    <add key=\"%s\" value=\"%s\" />\n", f.Name, escape(f.NuGet))
		onlyAzure = onlyAzure && f.Auth == protocol.AuthAzureArtifacts
	}
	if !onlyAzure {
		fmt.Fprintf(&b, "    <add key=\"nuget.org\" value=\"%s\" />\n", NuGetOrg)
	}
	b.WriteString("  </packageSources>\n")
	var creds strings.Builder
	for _, f := range feeds {
		if env := TokenEnv(f); env != "" {
			fmt.Fprintf(&creds, "    <%s>\n      <add key=\"Username\" value=\"smith\" />\n      <add key=\"ClearTextPassword\" value=\"%%%s%%\" />\n    </%s>\n", f.Name, env, f.Name)
		}
	}
	if creds.Len() > 0 {
		b.WriteString("  <packageSourceCredentials>\n" + creds.String() + "  </packageSourceCredentials>\n")
	}
	b.WriteString("</configuration>\n")
	return b.String()
}

// TokenEnv is the variable a feed's token is read from: the one smith.toml
// names, GITHUB_TOKEN for GitHub Packages, none for Azure Artifacts.
func TokenEnv(r *protocol.Registry) string {
	switch r.Auth {
	case protocol.AuthToken:
		return r.TokenEnv
	case protocol.AuthGitHubPackages:
		return "GITHUB_TOKEN"
	}
	return ""
}

func escape(s string) string {
	var b bytes.Buffer
	_ = xml.EscapeText(&b, []byte(s))
	return b.String()
}

// Of are the registries the projects share; the host sets the same install
// registry on each.
func Of(projects []protocol.Project) *protocol.Registries {
	for _, p := range projects {
		if p.Registries != nil {
			return p.Registries
		}
	}
	return nil
}
