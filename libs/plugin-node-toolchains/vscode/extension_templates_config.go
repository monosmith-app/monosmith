package vscode

import (
	"maps"

	"github.com/monosmith-app/monosmith/libs/plugin-node-toolchains/typescript"
)

// engine is the oldest VS Code the extension supports; @types/vscode
// follows it, never @latest (which tracks an unreleased VS Code).
const engine = "1.96.0"

// devDependencies are the root tooling; bump them deliberately.
var devDependencies = map[string]string{
	"@types/vscode": "~" + engine,
	"@vscode/vsce":  "^4.0.0",
	"esbuild":       "^0.28.2",
	"typescript":    "~6.0.3",
}

// publisherToken and kindToken stand for the Marketplace publisher and the
// project kind in the manifest; Generate replaces them.
const (
	publisherToken = "__PUBLISHER__"
	kindToken      = "__KIND__"
)

// templates are the extension: a manifest whose main is the bundle in the
// workspace's dist/ (staged beside it to pack), an entry point that
// registers a command, and the greeting slice the command shows.
var templates = withGreetingSlice(map[string]string{
	"[[.Dir]]/package.json": `{
  "name": "[[.Name]]",
  "displayName": "[[.Name]]",
  "description": "[[.Name]]",
  "publisher": "` + publisherToken + `",
  "version": "0.0.0",
  "license": "MIT",
  "engines": { "vscode": "^` + engine + `" },
  "categories": ["Other"],
  "main": "[[.Build]]/main.js",
  "activationEvents": [],
  "contributes": {
    "commands": [{ "command": "[[.Name]].hello", "title": "[[.Name]]: Hello" }]
  },
  "smith": { "kind": "__KIND__"[[if .Stack]], "stack": "[[.Stack]]"[[end]] },
  "scripts": {
    "build": "esbuild src/main.ts --bundle --platform=node --format=cjs --target=node20 --external:vscode --sourcemap --outfile=[[.Build]]/main.js",
    "typecheck": "tsc -p tsconfig.json --noEmit"
  }
}
`,
	"[[.Dir]]/tsconfig.json": `{
  "compilerOptions": {
    "target": "es2023",
    "lib": ["es2023"],
    "module": "preserve",
    "moduleResolution": "bundler",
    "strict": true,
    "isolatedModules": true,
    "skipLibCheck": true,
    "noEmit": true,
    "allowImportingTsExtensions": true,
    "verbatimModuleSyntax": true,
    "forceConsistentCasingInFileNames": true,
    "types": ["vscode"]
  },
  "include": ["src"]
}
`,
	"[[.Dir]]/src/main.ts": `import * as vscode from 'vscode'
import { greet } from './greeting/index.ts'

/**
 * Registers the extension's commands.
 * @param context - the extension's lifetime
 */
export function activate (context: vscode.ExtensionContext): void {
  context.subscriptions.push(vscode.commands.registerCommand('[[.Name]].hello', () => {
    void vscode.window.showInformationMessage(greet('world').message)
  }))
}

/** Nothing to release: every registration is in the context's subscriptions. */
export function deactivate (): void {}
`,
	"[[.Dir]]/README.md": `# [[.Name]]

A VS Code extension. Run the "[[.Name]]: Hello" command.

Generated by smith: ` + "`smith run package`" + ` packs it into a .vsix in dist/drop, and a
release publishes it to the Marketplace with the token in VSCE_PAT or, when smith.toml
sets [release] vsce_entra = true, as a Microsoft Entra ID app signed in by the workflow
(no token). With OVSX_PAT set it also publishes to Open VSX.
`,
})

func withGreetingSlice(files map[string]string) map[string]string {
	maps.Copy(files, typescript.GreetingSlice)
	return files
}
