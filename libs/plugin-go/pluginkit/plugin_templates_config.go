// The plugin keeps the protocol's promises (the checks smith plugin check runs).
func TestConformance(t *testing.T) {
	toPlugin, fromHost := io.Pipe()
	toHost, fromPlugin := io.Pipe()
	go func() { _ = serve.Serve(New("1.0.0"), toPlugin, fromPlugin) }()
	c, err := host.Connect(toHost, fromHost, host.Options{WorkspaceRoot: t.TempDir()})
	if err != nil {
		t.Fatal(err)
	}
	defer func() { _ = c.Close() }()
	if report := conformance.Check(c, conformance.Options{}); !report.OK() {
		t.Fatal(report.Failures())
	}
}
